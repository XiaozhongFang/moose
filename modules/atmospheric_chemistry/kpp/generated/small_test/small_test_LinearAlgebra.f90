! 
! KppSolve - sparse back substitution
!   Arguments :
!      JVS       - sparse Jacobian of variables
!      X         - Vector for variables
! 
! ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

SUBROUTINE KppSolve ( JVS, X )

! JVS - sparse Jacobian of variables
  REAL(kind=dp) :: JVS(LU_NONZERO)
! X - Vector for variables
  REAL(kind=dp) :: X(NVAR)

  X(2) = X(2)-JVS(3)*X(1)
  X(3) = X(3)-JVS(7)*X(1)-JVS(8)*X(2)
  X(4) = X(4)-JVS(12)*X(2)-JVS(13)*X(3)
  X(5) = X(5)-JVS(16)*X(2)-JVS(17)*X(3)-JVS(18)*X(4)
  X(5) = X(5)/JVS(19)
  X(4) = (X(4)-JVS(15)*X(5))/(JVS(14))
  X(3) = (X(3)-JVS(10)*X(4)-JVS(11)*X(5))/(JVS(9))
  X(2) = (X(2)-JVS(5)*X(3)-JVS(6)*X(5))/(JVS(4))
  X(1) = (X(1)-JVS(2)*X(3))/(JVS(1))
      
END SUBROUTINE KppSolve

